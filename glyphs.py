_cache = {}


def size(font):
    return FONTS[font][0], FONTS[font][1]


def pixels(font, ch):
    key = (font, ch)
    if key in _cache:
        return _cache[key]
    rows = FONTS[font][2].get(ch)
    out = []
    if rows:
        for ry in range(len(rows)):
            row = rows[ry]
            for rx in range(len(row)):
                if row[rx] == "#":
                    out.append((rx, ry))
    _cache[key] = out
    return out
